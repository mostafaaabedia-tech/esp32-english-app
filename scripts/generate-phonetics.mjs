// Generates phonetics.js (IPA per word + homophone lists) from the CMU Pronouncing Dictionary.
//
// Usage (only needed if you add NEW words to sentences.js):
//   npm install --no-save cmu-pronouncing-dictionary
//   node scripts/generate-phonetics.mjs
//
import fs from 'node:fs';
import { dictionary } from 'cmu-pronouncing-dictionary';

const src = fs.readFileSync(new URL('../sentences.js', import.meta.url), 'utf8');
const sentences = [...src.matchAll(/"([^"]+)"/g)].map((m) => m[1]);

const clean = (w) => w.toLowerCase().replace(/[’‘`]/g, "'").replace(/[^a-z']/g, '');
const words = [...new Set(sentences.flatMap((s) => s.split(/\s+/).map(clean)).filter(Boolean))].sort();

// Words missing from the dictionary can be added by hand here (ARPAbet).
const MANUAL = {
  hurtled: 'HH ER1 T AH0 L D',
  isomorphic: 'AY2 S AH0 M AO1 R F IH0 K',
};

const VOWELS = new Set(['AA','AE','AH','AO','AW','AY','EH','ER','EY','IH','IY','OW','OY','UH','UW']);
const IPA = {
  AA:'ɑ', AE:'æ', AH:'ʌ', AO:'ɔ', AW:'aʊ', AY:'aɪ', B:'b', CH:'tʃ', D:'d', DH:'ð', EH:'ɛ', ER:'ɝ',
  EY:'eɪ', F:'f', G:'g', HH:'h', IH:'ɪ', IY:'i', JH:'dʒ', K:'k', L:'l', M:'m', N:'n', NG:'ŋ',
  OW:'oʊ', OY:'ɔɪ', P:'p', R:'r', S:'s', SH:'ʃ', T:'t', TH:'θ', UH:'ʊ', UW:'u', V:'v', W:'w',
  Y:'j', Z:'z', ZH:'ʒ',
};
const VALID_ONSETS = new Set([
  'P L','P R','B L','B R','T R','D R','K L','K R','G L','G R','F L','F R','TH R','SH R',
  'S L','S M','S N','S P','S T','S K','S W','T W','K W','D W','G W','TH W',
  'P Y','B Y','T Y','D Y','K Y','G Y','F Y','V Y','M Y','N Y','L Y','S Y','HH Y','TH Y','Z Y',
  'S P L','S P R','S T R','S K R','S K W',
]);

function arpaToIpa(pron) {
  const ph = pron.split(' ').map((p) => {
    const m = p.match(/^([A-Z]+)([0-2])?$/);
    return { sym: m[1], stress: m[2] === undefined ? null : Number(m[2]) };
  });
  const isV = (p) => VOWELS.has(p.sym);
  const syllables = ph.filter(isV).length;

  // Where to put stress marks (only for words with 2+ syllables)
  const marks = new Map(); // index -> 'ˈ' | 'ˌ'
  if (syllables > 1) {
    ph.forEach((p, i) => {
      if (!isV(p) || (p.stress !== 1 && p.stress !== 2)) return;
      let j = i;
      while (j - 1 >= 0 && !isV(ph[j - 1]) && i - (j - 1) <= 3) j--;
      let start = i;
      if (j === 0) start = 0;                       // word-initial cluster
      else {
        for (let k = j; k < i; k++) {               // longest legal onset
          const cluster = ph.slice(k, i).map((x) => x.sym).join(' ');
          if (k === i - 1 || VALID_ONSETS.has(cluster)) { start = k; break; }
        }
      }
      marks.set(start, p.stress === 1 ? 'ˈ' : 'ˌ');
    });
  }

  return ph.map((p, i) => {
    let s = IPA[p.sym];
    if (p.sym === 'AH') s = p.stress === 0 ? 'ə' : 'ʌ';
    if (p.sym === 'ER') s = p.stress === 0 ? 'ɚ' : 'ɝ';
    return (marks.get(i) || '') + s;
  }).join('');
}

const strip = (pron) => pron.replace(/[0-9]/g, '');
const variants = (w) => {
  const out = [];
  if (dictionary[w]) out.push(dictionary[w]);
  for (let n = 1; n < 6 && dictionary[`${w}(${n})`]; n++) out.push(dictionary[`${w}(${n})`]);
  if (MANUAL[w]) out.push(MANUAL[w]);
  return out;
};

// phoneme string -> set of words that sound the same
const byPron = new Map();
for (const [key, pron] of Object.entries(dictionary)) {
  const base = key.replace(/\(\d+\)$/, '');
  if (!/^[a-z']+$/.test(base)) continue;
  const k = strip(pron);
  if (!byPron.has(k)) byPron.set(k, new Set());
  byPron.get(k).add(base);
}

const ipa = {};
const homophones = {};
const missing = [];
for (const w of words) {
  const v = variants(w);
  if (!v.length) { missing.push(w); continue; }
  ipa[w] = arpaToIpa(v[0]);
  const same = new Set();
  for (const pron of v) for (const x of byPron.get(strip(pron)) ?? []) if (x !== w) same.add(x);
  if (same.size) homophones[w] = [...same].sort().slice(0, 12);
}

const out =
`// AUTO-GENERATED by scripts/generate-phonetics.mjs from the CMU Pronouncing Dictionary.
// IPA = American English pronunciation. HOMOPHONES = words that sound identical (accepted by the checker).

export const IPA = ${JSON.stringify(ipa, null, 1)};

export const HOMOPHONES = ${JSON.stringify(homophones, null, 1)};
`;
fs.writeFileSync(new URL('../phonetics.js', import.meta.url), out);
console.log(`words: ${words.length}, with IPA: ${Object.keys(ipa).length}, with homophones: ${Object.keys(homophones).length}`);
console.log('missing from dictionary:', missing);
